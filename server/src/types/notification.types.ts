/**
 * Notification types mirroring the actual `notifications` table in Neon
 * PostgreSQL (schema inspected directly from the live database).
 *
 * Existing table columns:
 *   - user_id (NOT NULL, FK -> users.id): recipient is the authenticated user
 *   - title / message
 *   - type (varchar(30), NOT NULL, DEFAULT 'INFO'): no DB CHECK, so the app
 *     enforces the controlled vocabulary below.
 *   - is_read (boolean, NOT NULL, DEFAULT false)
 *   - related_entity_type / related_entity_id: optional link to alerts /
 *     interventions that the notification describes
 *   - created_at
 *
 * Index: (user_id, is_read) already exists and covers per-user list + unread
 * count queries; no schema change is required.
 */

/**
 * Controlled notification types.
 * The DB has no CHECK on `notifications.type`, so the app (types + validators)
 * is the single enforcement point. 'INFO' mirrors the column default; the other
 * values are the meaningful system events generated by Phase 12.
 */
export const NOTIFICATION_TYPES = [
  'HIGH_RISK_DETECTED',
  'RISK_WORSENED',
  'ALERT_CREATED',
  'INTERVENTION_RECOMMENDED',
  'INTERVENTION_STATUS_UPDATED',
  'INFO'
] as const;
export type NotificationType = (typeof NOTIFICATION_TYPES)[number];

/** Entity kinds a notification can point at via related_entity_type. */
export const NOTIFICATION_RELATED_ENTITY_TYPES = ['ALERT', 'INTERVENTION'] as const;
export type NotificationRelatedEntityType =
  (typeof NOTIFICATION_RELATED_ENTITY_TYPES)[number];

/** Input used to create a notification for the currently authenticated user. */
export interface CreateNotificationInput {
  userId: number;
  type: NotificationType;
  title: string;
  message: string;
  relatedEntityType?: NotificationRelatedEntityType | null;
  relatedEntityId?: number | null;
}

/** A row from the `notifications` table surfaced by the notification repository. */
export interface StoredNotification {
  id: number;
  userId: number;
  type: NotificationType;
  title: string;
  message: string;
  isRead: boolean;
  relatedEntityType: NotificationRelatedEntityType | null;
  relatedEntityId: number | null;
  createdAt: Date;
}